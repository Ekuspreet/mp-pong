export function makeStars(width, height, reduced) {
  const count = reduced
    ? 65
    : Math.min(190, Math.floor((width * height) / 7000))
  let seed = 907
  const random = () => ((seed = (seed * 16807) % 2147483647) - 1) / 2147483646
  return Array.from({ length: count }, (_, index) => ({
    x: random() * width,
    y: random() * height,
    size: 0.6 + random() * 2.2,
    alpha: 0.28 + random() * 0.65,
    phase: random() * Math.PI * 2,
    twinkleSpeed: 0.0007 + random() * 0.0011,
    layer: index % 3,
  }))
}

export function makeArtifacts(width, height, reduced) {
  if (reduced) return []
  return Array.from({ length: width < 700 ? 4 : 8 }, (_, index) => ({
    constellation:
      constellationPatterns[
        Math.floor(Math.random() * constellationPatterns.length)
      ],
    x: 0.05 * width + Math.random() * width * 0.9,
    y: 0.1 * height + Math.random() * height * 0.8,
    size: 10 + Math.random() * 11,
    rotation: Math.random() * Math.PI * 2,
    phase: index * 0.83 + Math.random() * Math.PI,
  }))
}
